#!/usr/bin/env python3
"""Install SecAudit's custom agent where Codex looks for agents.

    python3 install.py                 # into $CODEX_HOME/agents (default ~/.codex/agents)
    python3 install.py --project DIR   # into DIR/.codex/agents, for one project only
    python3 install.py --check         # report drift, write nothing; exit 1 if not current
    python3 install.py --uninstall     # remove what this script installed

A Codex plugin carries skills and hooks. It cannot carry a custom agent: Codex discovers those
in `$CODEX_HOME/agents/` and in a project's `.codex/agents/`, and nowhere inside a plugin. So
the `secaudit-verifier` agent that the plugin install gives a Claude Code session has to be put
in place by hand here, once. Without it nothing breaks — the skills fall back to a default agent
handed the verifier's instructions — but the named, read-only-sandboxed role is this file's job.

Only files this kit generated are ever replaced or removed: a file of the same name that does
not carry the generator's first line is somebody else's, and is left alone with a message.
"""
from __future__ import annotations

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "agents")
MARK = "# GENERATED by scripts/gen_codex.py from plugins/secaudit/"


def read(path: str) -> str | None:
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError:
        return None


def target_dir(args: argparse.Namespace) -> str:
    if args.project:
        return os.path.join(os.path.abspath(args.project), ".codex", "agents")
    home = os.environ.get("CODEX_HOME") or os.path.join(os.path.expanduser("~"), ".codex")
    return os.path.join(home, "agents")


def main() -> int:
    parser = argparse.ArgumentParser(description="Install SecAudit's Codex custom agent.")
    parser.add_argument("--project", metavar="DIR", help="install into DIR/.codex/agents")
    parser.add_argument("--check", action="store_true", help="report drift and write nothing")
    parser.add_argument("--uninstall", action="store_true", help="remove the installed agent")
    args = parser.parse_args()

    target = target_dir(args)
    agents = sorted(n for n in os.listdir(SOURCE) if n.endswith(".toml"))
    problems = 0
    for name in agents:
        wanted = read(os.path.join(SOURCE, name)) or ""
        path = os.path.join(target, name)
        current = read(path)
        ours = current is not None and current.startswith(MARK)

        if current is not None and not ours:
            print(f"left alone: {path} exists and was not installed by SecAudit")
            problems += 1
        elif args.uninstall:
            if current is None:
                print(f"not installed: {path}")
            elif args.check:
                print(f"would remove: {path}")
            else:
                os.remove(path)
                print(f"removed: {path}")
        elif current == wanted:
            print(f"current: {path}")
        elif args.check:
            print(f"{'stale' if current is not None else 'missing'}: {path}")
            problems += 1
        else:
            os.makedirs(target, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(wanted)
            print(f"{'updated' if current is not None else 'installed'}: {path}")

    if not args.check and not args.uninstall and not problems:
        print("Start a new Codex session to pick the agent up.")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
